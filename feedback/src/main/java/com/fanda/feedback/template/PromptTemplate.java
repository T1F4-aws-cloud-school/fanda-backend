package com.fanda.feedback.template;

public class PromptTemplate {

    public static String getComparePrompt(String baselineReport, String improvedReviewListText){
        return """
            아래 자료를 바탕으로 텍스트 기반 비교 분석 보고서를 작성해라. (PDF로 바로 인쇄됨)
            불필요한 수식/장식 금지, 간결한 한국어 사용.
            표는 ASCII(+, -, |, 공백)만 사용하며, **각 셀은 지정된 칸수로 우측 공백 패딩**해서 정렬할 것.
            (공백은 절대 줄이지 말 것)

            =========================
            개선 전/후 리뷰 비교 보고서
            =========================

            1) 요약

            - 개선 성과 핵심 3~5줄
            - 눈에 띄는 변화 2개는 수치/비율로 (근사치 허용)

            2) KPI 스냅샷(표)

            +----------------------+------------+------------+-----------+
            | 지표                 | 개선 전    | 개선 후    | 변화      |
            +----------------------+------------+------------+-----------+
            | 평균 평점            | x.xx       | y.yy       | ±a.aa     |
            | 중앙값 평점          | x          | y          | ±a        |
            | 부정 키워드 빈도     | n1건       | n2건       | ±d건      |
            | 긍정:부정 비율       | p1:q1      | p2:q2      | 개선/악화 |
            +----------------------+------------+------------+-----------+

            3) 개선 전 이슈(요약)

            - 상위 3~5개 불만과 한 줄 근거

            4) 개선 후 분석

            - 긍정 Top3(각 1줄 근거)
            - 부정 Top3(각 1줄 근거)

            5) 전/후 비교(핵심 이슈 기준, 표)

            (아래 표는 고정 칸폭으로 맞출 것: 항목[19칸], 개선 전[18칸], 개선 후[18칸], 판단[12칸])

            +-------------------+------------------+------------------+------------+
            | 항목              | 개선 전          | 개선 후          | 판단       |
            +-------------------+------------------+------------------+------------+
            | 이슈 #1           | (1줄)            | (1줄)            | 개선/동일  |
            | 이슈 #2           | (1줄)            | (1줄)            | 개선/동일  |
            | 이슈 #3           | (1줄)            | (1줄)            | 개선/동일  |
            +-------------------+------------------+------------------+------------+

            6) 권고사항(Next Actions)

            - 3~5개 체크리스트, 각 항목에 [우선순위/난이도/예상효과] 표기

            7) 결론

            - 종합 평가 1단락, 추적할 KPI 2개, 재검토 시점(예: 4주)

            ----------------------------------------

            [개선 전 리포트(텍스트)]
            %s

            [개선 후 리뷰(목록)]
            %s

            ----------------------------------------
            """.formatted(baselineReport, improvedReviewListText);
    }
}